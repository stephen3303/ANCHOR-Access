"""Write the web kit's palettes (ui/palettes.css) from the Access kit's palette
source, tools/make_themes.py, so the web and Access front ends share one set of
named palettes and switch the same way. Never edit palettes.css by hand: edit
make_themes.py and run

    python web/kit/tools/make_web_palettes.py access/tools/make_themes.py

Each palette becomes a [data-palette="<key>"] block of CSS variables named after
the Access color roles: CLR_PRIMARY -> --clr-primary. The first palette (the
build palette) is also the :root default.
"""
import json
import os
import runpy
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
src = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.join(HERE, "..", "..", "..", "access", "tools", "make_themes.py")
out = os.path.join(HERE, "..", "ui", "palettes.css")

# make_themes.py writes VBA modules as it runs; let it write them somewhere
# throwaway and keep only its palette table.
with tempfile.TemporaryDirectory() as tmp:
    os.makedirs(os.path.join(tmp, "themes", "light"))
    os.makedirs(os.path.join(tmp, "modules"))
    argv, stdout = sys.argv, sys.stdout
    sys.argv = [src, tmp]
    sys.stdout = open(os.devnull, "w")
    try:
        g = runpy.run_path(src, run_name="make_themes")
    finally:
        sys.stdout.close()
        sys.argv, sys.stdout = argv, stdout

def var(key):
    return "--" + key.lower().replace("_", "-")

def block(sel, pal):
    lines = [f"{sel} {{", f"  color-scheme: {'dark' if pal['dark'] else 'light'};"]
    lines += [f"  {var(k)}: rgb({r} {gr} {b});" for k, (r, gr, b) in pal["c"].items() if not k.startswith("PRINT_")]
    lines.append("}")
    return "\n".join(lines)

pals = g["PALETTES"]
parts = [
    "/* Generated by web/kit/tools/make_web_palettes.py from access/tools/make_themes.py. Do not edit. */",
    "/* KIT_PALETTES: " + json.dumps([{"key": p["key"], "name": p["name"], "dark": p["dark"]} for p in pals]) + " */",
    block(":root, [data-palette=\"%s\"]" % pals[0]["key"], pals[0]),
]
parts += [block(f'[data-palette="{p["key"]}"]', p) for p in pals[1:]]
with open(out, "w", newline="\n") as f:
    f.write("\n\n".join(parts) + "\n")

# The list the palette picker shows, as a module the UI imports.
with open(os.path.join(HERE, "..", "ui", "palettes.ts"), "w", newline="\n") as f:
    f.write("// Generated by web/kit/tools/make_web_palettes.py. Do not edit.\n")
    f.write("export const PALETTES = " + json.dumps([{"key": p["key"], "name": p["name"], "dark": p["dark"]} for p in pals], indent=2) + " as const;\n")
print(f"{len(pals)} palettes -> {os.path.normpath(out)}")
